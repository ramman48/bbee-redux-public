/* char-nine: the Magic Arts chord's refund (build_nine.py arts_chord). The design: Magic Arts is switched on or
   off by pressing the Attack and Skill buttons at the same time.
   The engine has no two-button rows, so her Attack and Skill starters switch to a toggle (nine_arts__<move>) when the
   other button is pressed within their first moments. A Skill starter spent its MP when its row started (the engine
   applies a row's Mps as the step starts), so when a toggle follows one of her Skill starters this puts back exactly
   what that starter took: her MP and SP as they were the frame before it began, never more (regeneration in between
   is not added). Attack starters cost nothing.
   GENERATED by build_nine.py: edit js/arts_chord.tpl.js, not js/arts_chord.js.
   Appended to data/js/window/battle/BattleUI (module scope: Util_1, BattleJs_1). Runs from globalThis.BB_HUD_TICKS
   (bbee-sdk >= 0.3.3: BattleUI.LateUpdateWindow, after every C# Update). */
(function () {
  var G = globalThis, U = Util_1.U;
  var T = (G.BB_HUD_TICKS = G.BB_HUD_TICKS || {}); if (T["char-nine/arts-chord"]) return;
  var ACTOR = "200401", PREFIX = "nine_arts__", SKILLS = ["B2", "nine_gale", "nine_hail", "nine_bloom"], SLOTS = [2, 3];   // gauge slots: 2 MP, 3 SP
  var S = { pl: null, nine: false, id: -1, name: "", last: null, start: null };

  function isNine(p) {
    if (S.pl === p) return S.nine;
    var id = ""; try { id = String(p.ActionGroupID) } catch (e) {}
    if (id !== ACTOR) try { var fa = BattleJs_1.default.Instance.GetFesActor(); if (fa) id = String(fa.id) } catch (e) {}
    S.pl = p; S.nine = id === ACTOR; S.id = -1; S.last = null; S.start = null; return S.nine;
  }
  function gauges(p) { return SLOTS.map(function (s) { return U.FpToFloat(p.Attr.GetMP(s)) }) }
  // the refund: what the Skill starter took, measured from the frame before it began (0..100 per gauge)
  function refund(p, before, now) {
    for (var i = 0; i < SLOTS.length; i++) {
      var d = before[i] - now[i];
      if (d > 0.01) p.Attr.ChangeMPBy(U.FloatToFp(Math.min(d, 100)), SLOTS[i]);
    }
  }
  function tick() {
    var b = BattleJs_1.default.Instance, p = b && b.Battle && b.Battle.PlayerSelf;
    if (!p || !isNine(p)) return;
    var am = p.ActionMgr, id = am.ActionChangeAutoId, now = gauges(p);
    if (S.last === null) { S.id = id; S.name = String(am.CurrentActionName); S.last = now; return }
    if (id !== S.id) {                                     // her action changed since the last frame
      var name = String(am.CurrentActionName);
      if (name.indexOf(PREFIX) === 0 && SKILLS.indexOf(S.name) >= 0 && S.start) { refund(p, S.start, now); now = gauges(p) }
      S.start = S.last;                                    // the gauges the frame before this action began
      S.id = id; S.name = name;
    }
    S.last = now;
  }
  T["char-nine/arts-chord"] = tick;
})();
